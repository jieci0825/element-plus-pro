/**
 * 模拟请求函数
 * @param {Object} params - 请求参数
 * @param {number} params.page - 页码
 * @param {number} params.pageSize - 每页条数
 * @param {*} params[key] - 其他动态筛选字段
 * @returns {Promise}
 */
export const getUserList = (params) => {
    return new Promise((resolve) => {
        setTimeout(() => {
            const { page = 1, pageSize = 10, ...filterParams } = params

            // 先根据条件筛选数据
            let filteredList = mockUserList

            // 遍历筛选参数，进行动态条件查询
            if (Object.keys(filterParams).length > 0) {
                filteredList = mockUserList.filter((item) => {
                    // 所有条件都要满足（AND 逻辑）
                    return Object.keys(filterParams).every((key) => {
                        const filterValue = filterParams[key]
                        const itemValue = item[key]

                        // 如果数据中不存在该字段，则不匹配
                        if (!(key in item)) {
                            return false
                        }

                        // 如果筛选值为 null 或 undefined，跳过该条件
                        if (
                            filterValue === null ||
                            filterValue === undefined ||
                            filterValue === ''
                        ) {
                            return true
                        }

                        // 字符串类型进行模糊匹配（包含即可）
                        if (
                            typeof filterValue === 'string' &&
                            typeof itemValue === 'string'
                        ) {
                            return itemValue
                                .toLowerCase()
                                .includes(filterValue.toLowerCase())
                        }

                        // 其他类型进行精确匹配
                        return itemValue === filterValue
                    })
                })
            }

            // 再进行分页
            const start = (page - 1) * pageSize
            const end = start + pageSize
            const list = filteredList.slice(start, end)

            resolve({
                code: 200,
                data: {
                    list,
                    total: filteredList.length
                }
            })
        }, 500)
    })
}
